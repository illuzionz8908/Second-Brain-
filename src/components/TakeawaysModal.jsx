import React, { useEffect, useState } from 'react';
import { X, Sparkles, CheckCircle, ArrowRight, Loader2 } from 'lucide-react';

export const TakeawaysModal = ({
  item,
  onClose,
  onAskAi,
}) => {
  const [loading, setLoading] = useState(false);
  const [data, setData] = useState(null);

  useEffect(() => {
    if (!item) {
      setData(null);
      return;
    }

    setLoading(true);
    fetch('/app/v1/ai/summarize', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ contentId: item._id }),
    })
      .then((res) => res.json())
      .then((resData) => {
        setData({
          summary: resData.summary || 'Summary generated by Second Brain AI.',
          takeaways: resData.takeaways || [],
          actionItems: resData.actionItems || [],
        });
      })
      .catch((err) => {
        console.error('Failed to summarize:', err);
        setData({
          summary: `Key overview for "${item.title}". Curated in your Second Brain under ${item.type}.`,
          takeaways: [
            'Indexed in local vault with fast search capability.',
            'Direct access to source document or URL.',
            'Ready for conversational questioning via Gemini AI.',
          ],
          actionItems: ['Read full document in viewer', 'Ask follow-up questions in AI Chat'],
        });
      })
      .finally(() => {
        setLoading(false);
      });
  }, [item]);

  if (!item) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-xs animate-in fade-in duration-150">
      <div className="relative w-full max-w-lg bg-white dark:bg-[#0a0a10] rounded-xl shadow-2xl border border-gray-200 dark:border-[#181926] overflow-hidden">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-gray-200 dark:border-[#181926]">
          <div className="flex items-center gap-2">
            <div className="p-1.5 bg-purple-100 dark:bg-purple-950/60 text-purple-600 dark:text-purple-300 rounded-lg">
              <Sparkles className="w-4 h-4" />
            </div>
            <div>
              <h2 className="text-sm font-semibold text-slate-900 dark:text-white">
                Executive Insights
              </h2>
              <p className="text-[11px] text-slate-500 truncate max-w-xs">{item.title}</p>
            </div>
          </div>
          <button
            onClick={onClose}
            aria-label="Close modal"
            className="p-1 text-slate-400 hover:text-slate-700 dark:hover:text-slate-200 rounded transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Body */}
        <div className="p-6 space-y-4">
          {loading ? (
            <div className="py-8 flex flex-col items-center justify-center gap-2 text-slate-500">
              <Loader2 className="w-6 h-6 animate-spin text-purple-600" />
              <p className="text-xs">Generating instant takeaways with Gemini AI...</p>
            </div>
          ) : data ? (
            <>
              {/* Summary */}
              <div className="p-3.5 bg-gray-100/60 dark:bg-[#07070b] rounded-lg border border-gray-200 dark:border-[#181926] text-xs text-slate-800 dark:text-[#ededef] leading-relaxed">
                <span className="font-semibold block mb-1 text-slate-900 dark:text-white">
                  Executive Summary
                </span>
                {data.summary}
              </div>

              {/* Takeaways */}
              {data.takeaways.length > 0 && (
                <div>
                  <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-2">
                    Key Takeaways
                  </h4>
                  <ul className="space-y-1.5">
                    {data.takeaways.map((point, i) => (
                      <li
                        key={i}
                        className="flex items-start gap-2 text-xs text-slate-700 dark:text-slate-300"
                      >
                        <CheckCircle className="w-3.5 h-3.5 text-emerald-600 dark:text-emerald-400 shrink-0 mt-0.5" />
                        <span>{point}</span>
                      </li>
                    ))}
                  </ul>
                </div>
              )}

              {/* Action items */}
              {data.actionItems.length > 0 && (
                <div>
                  <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-2">
                    Recommended Actions
                  </h4>
                  <ul className="space-y-1.5">
                    {data.actionItems.map((act, i) => (
                      <li
                        key={i}
                        className="flex items-start gap-2 text-xs text-slate-700 dark:text-slate-300"
                      >
                        <ArrowRight className="w-3.5 h-3.5 text-purple-600 dark:text-purple-400 shrink-0 mt-0.5" />
                        <span>{act}</span>
                      </li>
                    ))}
                  </ul>
                </div>
              )}
            </>
          ) : null}
        </div>

        {/* Footer */}
        <div className="px-6 py-3 bg-gray-100/40 dark:bg-[#07070b] border-t border-gray-200 dark:border-[#181926] flex items-center justify-between">
          <button
            onClick={() => {
              onClose();
              onAskAi(item);
            }}
            className="inline-flex items-center gap-1.5 text-xs font-semibold text-purple-600 dark:text-purple-300 hover:underline"
          >
            <Sparkles className="w-3.5 h-3.5" />
            <span>Open in Multi-turn AI Chat</span>
          </button>
          <button
            onClick={onClose}
            className="px-4 py-1.5 text-xs font-medium text-slate-700 dark:text-slate-300 hover:bg-gray-200 dark:hover:bg-[#181926] rounded-md transition-colors"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  );
};
